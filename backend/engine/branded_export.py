"""Vnicorn Investments branded exports: one template for Excel (.xlsx) and PDF reports."""

from __future__ import annotations

import io
from datetime import datetime, timezone

BRAND = "Vnicorn Investments"
VIOLET, CYAN, INK, MUTED = "7C3AED", "06B6D4", "0F172A", "64748B"
DISCLAIMER = "Generated by Vnicorn Investments. For information only, not investment advice. Prices may be delayed."

# column spec: (key, header, kind) with kind in text | date | money | number | pct | signed_money
Column = tuple[str, str, str]


def _now() -> str:
    return datetime.now(timezone.utc).strftime("%Y-%m-%d %H:%M UTC")


def to_xlsx(title: str, subtitle: str, columns: list[Column], rows: list[dict], totals: dict | None = None) -> bytes:
    from openpyxl import Workbook
    from openpyxl.styles import Alignment, Border, Font, PatternFill, Side
    from openpyxl.utils import get_column_letter

    wb = Workbook()
    ws = wb.active
    ws.title = title[:31]
    n = len(columns)
    last = get_column_letter(n)
    ws.merge_cells(f"A1:{last}1")
    ws["A1"] = f"🦄  {BRAND}"
    ws["A1"].font = Font(size=16, bold=True, color="FFFFFF")
    ws["A1"].fill = PatternFill("solid", fgColor=VIOLET)
    ws["A1"].alignment = Alignment(vertical="center", indent=1)
    ws.row_dimensions[1].height = 30
    ws.merge_cells(f"A2:{last}2")
    ws["A2"] = title
    ws["A2"].font = Font(size=13, bold=True, color=INK)
    ws.merge_cells(f"A3:{last}3")
    ws["A3"] = f"{subtitle} · exported {_now()}"
    ws["A3"].font = Font(size=9, color=MUTED)
    head_row = 5
    thin = Side(style="thin", color="E2E8F0")
    for c, (_, header, kind) in enumerate(columns, 1):
        cell = ws.cell(row=head_row, column=c, value=header)
        cell.font = Font(bold=True, color="FFFFFF")
        cell.fill = PatternFill("solid", fgColor=INK)
        cell.alignment = Alignment(horizontal="right" if kind not in ("text", "date") else "left")
    fmt = {"money": '"$"#,##0.00', "signed_money": '+"$"#,##0.00;-"$"#,##0.00', "number": "#,##0.####", "pct": '+0.00"%";-0.00"%"', "date": "yyyy-mm-dd"}
    for r_i, row in enumerate(rows, head_row + 1):
        for c, (key, _, kind) in enumerate(columns, 1):
            v = row.get(key)
            if kind == "date" and isinstance(v, str):
                try:
                    v = datetime.fromisoformat(v[:10])
                except ValueError:
                    pass
            cell = ws.cell(row=r_i, column=c, value=v)
            if kind in fmt:
                cell.number_format = fmt[kind]
            if kind in ("signed_money", "pct") and isinstance(v, (int, float)):
                cell.font = Font(color="16A34A" if v >= 0 else "DC2626")
            cell.border = Border(bottom=thin)
            if (r_i - head_row) % 2 == 0:
                cell.fill = PatternFill("solid", fgColor="F8FAFC")
    end = head_row + len(rows)
    if totals:
        end += 1
        for c, (key, _, kind) in enumerate(columns, 1):
            v = totals.get(key)
            cell = ws.cell(row=end, column=c, value=v if v is not None else ("Total" if c == 1 else None))
            cell.font = Font(bold=True)
            cell.border = Border(top=Side(style="medium", color=INK))
            if kind in fmt and v is not None:
                cell.number_format = fmt[kind]
    ws.cell(row=end + 2, column=1, value=DISCLAIMER).font = Font(size=8, italic=True, color=MUTED)
    ws.freeze_panes = ws.cell(row=head_row + 1, column=1)
    for c, (key, header, kind) in enumerate(columns, 1):
        width = max([len(str(header))] + [len(f"{r.get(key):,}" if isinstance(r.get(key), float) else str(r.get(key) or "")) for r in rows[:500]]) + 3
        ws.column_dimensions[get_column_letter(c)].width = min(max(width, 9), 40)
    buf = io.BytesIO()
    wb.save(buf)
    return buf.getvalue()


def _fmt(v, kind: str) -> str:
    if v is None or v == "":
        return "—"
    if kind == "money":
        return f"${v:,.2f}"
    if kind == "signed_money":
        return f"{'+' if v >= 0 else '−'}${abs(v):,.2f}"
    if kind == "pct":
        return f"{v:+.2f}%"
    if kind == "number":
        return f"{v:,.4f}".rstrip("0").rstrip(".")
    return str(v)


def to_pdf(title: str, subtitle: str, columns: list[Column], rows: list[dict], totals: dict | None = None) -> bytes:
    from reportlab.lib import colors
    from reportlab.lib.pagesizes import A4, landscape
    from reportlab.lib.units import mm
    from reportlab.platypus import SimpleDocTemplate, Spacer, Table, TableStyle
    from reportlab.platypus.flowables import Flowable

    violet, cyan, ink, muted = (colors.HexColor("#" + c) for c in (VIOLET, CYAN, INK, MUTED))

    class Header(Flowable):
        def __init__(self, width):
            super().__init__()
            self.width, self.height = width, 26 * mm

        def draw(self):
            c = self.canv
            c.setFillColor(violet)
            c.roundRect(0, 8 * mm, self.width, 18 * mm, 3 * mm, stroke=0, fill=1)
            # logo mark: a rounded square with a gradient-like stripe and a "V"
            c.setFillColor(colors.white)
            c.roundRect(5 * mm, 11 * mm, 12 * mm, 12 * mm, 2.5 * mm, stroke=0, fill=1)
            c.setFillColor(cyan)
            c.setFont("Helvetica-Bold", 14)
            c.drawCentredString(11 * mm, 14.2 * mm, "V")
            c.setFillColor(colors.white)
            c.setFont("Helvetica-Bold", 15)
            c.drawString(21 * mm, 17.5 * mm, BRAND)
            c.setFont("Helvetica", 8)
            c.drawString(21 * mm, 13 * mm, "Smarter stock research")
            c.setFillColor(ink)
            c.setFont("Helvetica-Bold", 12)
            c.drawString(0, 2.5 * mm, title)
            c.setFillColor(muted)
            c.setFont("Helvetica", 8)
            c.drawRightString(self.width, 2.5 * mm, f"{subtitle} · exported {_now()}")

    buf = io.BytesIO()
    page = landscape(A4) if len(columns) > 6 else A4

    def footer(canvas, doc):
        canvas.saveState()
        canvas.setFont("Helvetica", 7)
        canvas.setFillColor(muted)
        canvas.drawString(doc.leftMargin, 8 * mm, DISCLAIMER)
        canvas.drawRightString(page[0] - doc.rightMargin, 8 * mm, f"Page {doc.page}")
        canvas.restoreState()

    doc = SimpleDocTemplate(buf, pagesize=page, leftMargin=12 * mm, rightMargin=12 * mm, topMargin=10 * mm, bottomMargin=16 * mm,
                            title=f"{BRAND} · {title}", author=BRAND)
    data = [[h for _, h, _ in columns]] + [[_fmt(r.get(k), kind) for k, _, kind in columns] for r in rows]
    if totals:
        data.append([_fmt(totals.get(k), kind) if totals.get(k) is not None else ("Total" if i == 0 else "") for i, (k, _, kind) in enumerate(columns)])
    avail = page[0] - 24 * mm
    weights = [2.2 if kind == "text" and k in ("name",) else 1.0 for k, _, kind in columns]
    t = Table(data, repeatRows=1, hAlign="LEFT", colWidths=[avail * w / sum(weights) for w in weights])
    style = [
        ("BACKGROUND", (0, 0), (-1, 0), ink), ("TEXTCOLOR", (0, 0), (-1, 0), colors.white),
        ("FONT", (0, 0), (-1, 0), "Helvetica-Bold", 8), ("FONT", (0, 1), (-1, -1), "Helvetica", 8),
        ("ROWBACKGROUNDS", (0, 1), (-1, -1), [colors.white, colors.HexColor("#F8FAFC")]),
        ("LINEBELOW", (0, 0), (-1, -1), 0.25, colors.HexColor("#E2E8F0")),
        ("TOPPADDING", (0, 0), (-1, -1), 4), ("BOTTOMPADDING", (0, 0), (-1, -1), 4),
    ]
    for i, (_, _, kind) in enumerate(columns):
        if kind not in ("text", "date"):
            style.append(("ALIGN", (i, 0), (i, -1), "RIGHT"))
        if kind in ("signed_money", "pct"):
            for r_i, r in enumerate(rows, 1):
                v = r.get(columns[i][0])
                if isinstance(v, (int, float)):
                    style.append(("TEXTCOLOR", (i, r_i), (i, r_i), colors.HexColor("#16A34A" if v >= 0 else "#DC2626")))
    if totals:
        style += [("FONT", (0, -1), (-1, -1), "Helvetica-Bold", 8), ("LINEABOVE", (0, -1), (-1, -1), 1, ink)]
    t.setStyle(TableStyle(style))
    doc.build([Header(page[0] - 24 * mm), Spacer(1, 3 * mm), t], onFirstPage=footer, onLaterPages=footer)
    return buf.getvalue()


